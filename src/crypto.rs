//! Minimal crypto for calculator-gated engines (swisscows): SHA-256 +
//! base64url encode/decode. Pure Rust, no deps, stack-only buffers.
//! Standard FIPS-180 constants; verified against `hashlib.sha256` and
//! `base64.urlsafe_b64*` vectors in the offline suite.

